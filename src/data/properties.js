export function getCategory(id) {
  return categories.find((category) => category.id === id);
}

export function getTaluka(id) {
  return talukas.find((taluka) => taluka.id === id);
}

export function getProjectsByVillage(villageId, categoryId) {
  return projects.filter((project) => {
    const villageMatches = project.village === villageId;
    const categoryMatches = categoryId ? project.category === categoryId : true;
    return villageMatches && categoryMatches;
  });
}

export function getProject(id) {
  return projects.find((project) => project.id === id);
}
